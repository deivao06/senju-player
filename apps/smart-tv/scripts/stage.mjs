await cp(`platforms/${platform}`, out, { recursive: true });
// Launcher icon uses the existing Senju palette and an authored geometric S.
// Authored simple S glyph at 80×80. No image dependency in the app or build.
function crc(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) {
    c ^= b;
    for (let i = 0; i < 8; i++) c = (c >>> 1) ^ (c & 1 ? 0xedb88320 : 0);
  }
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(name, data) {
  const n = Buffer.from(name),
    length = Buffer.alloc(4),
    sum = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  sum.writeUInt32BE(crc(Buffer.concat([n, data])));
  return Buffer.concat([length, n, data, sum]);
}
const size = 80,
  raw = Buffer.alloc((size * 4 + 1) * size);
for (let y = 0; y < size; y++)
  for (let x = 0; x < size; x++) {
    const ink =
      (y >= 20 && y < 28 && x >= 23 && x < 57) ||
      (y >= 28 && y < 36 && x >= 23 && x < 31) ||
      (y >= 36 && y < 44 && x >= 23 && x < 57) ||
      (y >= 44 && y < 52 && x >= 49 && x < 57) ||
      (y >= 52 && y < 60 && x >= 23 && x < 57);
    const offset = y * (size * 4 + 1) + 1 + x * 4;
    raw.set(ink ? [52, 239, 125, 255] : [6, 11, 9, 255], offset);
  }
const header = Buffer.alloc(13);
header.writeUInt32BE(size);
header.writeUInt32BE(size, 4);
header[8] = 8;
header[9] = 6;
await writeFile(
  resolve(out, 'icon.png'),
  Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]),
);
await writeFile(
  resolve(out, 'icon.png.json'),
  JSON.stringify(
    {
      origin:
        'Authored geometric S launcher glyph; Senju colors from DESIGN.md. Generated by scripts/stage.mjs.',
    },
    null,
    2,
  ),
);
